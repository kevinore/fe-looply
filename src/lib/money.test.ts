import { formatCop } from './money';

describe('formatCop', () => {
  it.each([
    [42000, '$42.000'],
    [0, '$0'],
    [999, '$999'],
    [1000, '$1.000'],
    [1248000, '$1.248.000'],
    [40600, '$40.600'],
    [-1400, '-$1.400'],
    [1399.6, '$1.400'],
  ])('%d → %s', (n, s) => expect(formatCop(n)).toBe(s));
});
